#!/usr/bin/env python3
"""Renders the Velixo symbol as terminal half-block cells and writes src/Velixo.Cli/Output/VelixoSymbol.cs.

Usage: python3 scripts/render-symbol.py <symbol.png> [columns] [--shape <flat.png>]

With --shape, the colours come from the first image and the pixels drawn come from the second,
which is how the gradient artwork (no gaps between the bars) keeps the weave of the flat artwork.

Each terminal cell covers one pixel column and two pixel rows: the upper half block carries the
top pixel's colour in the foreground, the lower pixel's colour in the background. A PNG that
carries colour is sampled as it is. A black-and-white PNG gets the brand gradient computed per
bar: green to light blue along the bar that passes over, deep blue with light ends underneath.
"""
import math
import sys
from pathlib import Path

from PIL import Image

OVER = [(0x2e, 0xf0, 0xa0), (0x52, 0xdc, 0xd0), (0x7f, 0xb9, 0xff), (0x8c, 0xa0, 0xff)]
UNDER = [(0x7f, 0xbb, 0xff), (0x2b, 0x5c, 0xff), (0x2b, 0x5c, 0xff), (0x7f, 0xba, 0xff)]


def ramp(stops, t):
    t = min(max(t, 0.0), 1.0) * (len(stops) - 1)
    i = min(int(t), len(stops) - 2)
    f = t - i
    a, b = stops[i], stops[i + 1]
    return tuple(round(a[k] + (b[k] - a[k]) * f) for k in range(3))


def brand_colour(x, y):
    """Colour of a symbol pixel at normalised (x, y) in [-1, 1], from the bar it belongs to."""
    over_distance = abs(x - y)
    under_distance = abs(x + y)
    if over_distance <= under_distance:
        return ramp(OVER, (x + y + 2) / 4)
    return ramp(UNDER, (x - y + 2) / 4)


def cells(image, columns, shape=None):
    rows = columns // 2
    small = image.convert("RGBA").resize((columns, rows * 2), Image.LANCZOS)
    mask = shape.convert("RGBA").resize((columns, rows * 2), Image.LANCZOS) if shape is not None else small
    width, height = small.size

    def sample(px, py):
        r, g, b, a = small.getpixel((px, py))
        if mask.getpixel((px, py))[3] < 128 or a < 128:
            return None
        if r > 40 or g > 40 or b > 40:
            return (r, g, b)
        return brand_colour(px / (width - 1) * 2 - 1, py / (height - 1) * 2 - 1)

    table = []
    for row in range(rows):
        line = []
        for col in range(columns):
            top = sample(col, 2 * row)
            bottom = sample(col, 2 * row + 1)
            line.append((top, bottom))
        table.append(line)
    return table


def hex6(c):
    return "------" if c is None else "%02x%02x%02x" % c


def main():
    arguments = sys.argv[1:]
    shape = Image.open(arguments[arguments.index("--shape") + 1]) if "--shape" in arguments else None
    positional = [a for i, a in enumerate(arguments) if a != "--shape" and (i == 0 or arguments[i - 1] != "--shape")]
    source = Path(positional[0])
    columns = int(positional[1]) if len(positional) > 1 else 24
    table = cells(Image.open(source), columns, shape)
    target = Path(__file__).resolve().parent.parent / "src" / "Velixo.Cli" / "Output" / "VelixoSymbol.cs"
    lines = [
        "namespace Velixo.Cli.Output;",
        "",
        "/// <summary>",
        "/// The Velixo symbol as terminal cells, generated by scripts/render-symbol.py from the brand PNG.",
        "/// Each cell is the top pixel's colour, the bottom pixel's colour, as six hex digits each or dashes",
        "/// for a transparent pixel. Do not edit by hand: run the script.",
        "/// </summary>",
        "public static class VelixoSymbol",
        "{",
        f"    public const int Columns = {columns};",
        "",
        f"    public const int Rows = {len(table)};",
        "",
        "    public static readonly string[] Cells =",
        "    [",
    ]
    for line in table:
        lines.append('        "' + "".join(hex6(top) + hex6(bottom) for top, bottom in line) + '",')
    lines += ["    ];", "}", ""]
    target.write_text("\n".join(lines))
    print(f"wrote {target} ({columns}x{len(table)} cells)")


if __name__ == "__main__":
    main()
