#!/bin/sh
# Writes the Homebrew formula for a Velixo CLI release to stdout.
#
#   scripts/homebrew-formula.sh 1.0.2 checksums.txt > Formula/velixo.rb
#
# checksums.txt is the release's own file, as `sha256sum velixo-*` writes it. The formula installs
# the signed binaries from the GitHub Release; Homebrew never builds the CLI from source.
set -eu

if [ "$#" -ne 2 ]; then
  echo "usage: $0 VERSION CHECKSUMS_FILE" >&2
  exit 2
fi

version=$1
checksums=$2
base="https://github.com/VelixoSolutions/velixo-cli/releases/download/v$version"

sum() {
  file="velixo-$version-$1.tar.gz"
  value=$(awk -v f="$file" '$2 == f || $2 == "*" f { print $1 }' "$checksums")
  if [ -z "$value" ]; then
    echo "$checksums has no sum for $file" >&2
    exit 1
  fi
  echo "$value"
}

osx_arm64=$(sum osx-arm64)
osx_x64=$(sum osx-x64)
linux_arm64=$(sum linux-arm64)
linux_x64=$(sum linux-x64)

cat <<EOF
# Generated by scripts/homebrew-formula.sh from the release's checksums.txt. Do not edit by hand:
# the release workflow rewrites this file for every release.
class Velixo < Formula
  desc "Query an ERP, run ERP commands and imports from the command line"
  homepage "https://github.com/VelixoSolutions/velixo-cli"
  version "$version"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/velixo-$version-osx-arm64.tar.gz"
      sha256 "$osx_arm64"
    end
    on_intel do
      url "$base/velixo-$version-osx-x64.tar.gz"
      sha256 "$osx_x64"
    end
  end

  on_linux do
    on_arm do
      url "$base/velixo-$version-linux-arm64.tar.gz"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/velixo-$version-linux-x64.tar.gz"
      sha256 "$linux_x64"
    end
  end

  def install
    bin.install "velixo"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/velixo --version")
  end
end
EOF
